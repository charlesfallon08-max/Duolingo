export function findLesson(unitId: string, lessonId: string) {
  const unit = course.find((u) => u.id === unitId);
  const lesson = unit?.lessons.find((l) => l.id === lessonId);
  if (!unit || !lesson) throw new Error(`Leçon introuvable : ${unitId}/${lessonId}`);
  return { unit, lesson };
}
